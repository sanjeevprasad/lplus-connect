    #[test]
    fn dbs_frame_matches_castpush_golden() {
        let golden = hex::decode(GOLDEN_HEX).expect("golden is hex");
        let frame = dbs_frame(GOLDEN_KEY, GOLDEN_VALUE, GOLDEN_SEQ);
        assert_eq!(frame, golden, "frame drift vs /tmp/castpush.py golden");
        assert_eq!(frame.len(), 537);
    }

    #[test]
    fn dbs_frame_header_layout_is_exact() {
        let frame = dbs_frame(GOLDEN_KEY, GOLDEN_VALUE, GOLDEN_SEQ);
        // wrapper: >HH(len(payload)+2, 0x0020)
        assert_eq!(&frame[0..2], &((frame.len() - 4 + 2) as u16).to_be_bytes());
        assert_eq!(&frame[2..4], &[0x00, 0x20]);
        // payload prefix: 0x00 + >H tid
        assert_eq!(frame[4], 0x00);
        assert_eq!(&frame[5..7], &TID.to_be_bytes());
        // 52-byte dbr.a header at frame[7..59]
        assert_eq!(&frame[7..13], &[0xa1, 0xb2, 0xc3, 0xd4, 0xe5, 0xf6]); // from
        assert_eq!(&frame[13..21], &GOLDEN_SEQ.to_be_bytes()); // seq
        assert_eq!(&frame[21..27], &[0x01, 0x23, 0x45, 0x67, 0x89, 0xab]); // to
        assert_eq!(&frame[27..33], &[0x01, 0x23, 0x45, 0x67, 0x89, 0xab]); // id = to
        assert_eq!(frame[33], 42); // dbrMsgType -> DbsDataReceiver
        assert_eq!(frame[34], 1); // version
        assert!(frame[35..59].iter().all(|&b| b == 0)); // zero tail
        assert_eq!(&frame[59..61], b"{\""); // payload JSON starts
    }

