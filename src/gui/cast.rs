//! Cast / ODMF product lane behind the panel's `#/cast` tab: the Rust
//! twin of `/tmp/castpush.py` (unencrypted DbsMessage DataBus frames on the
//! live :46888 session), the two-push phone trigger that arms the ODMF
//! mirroring sink, the `lplus_status` snapshot, and the whitelist that
//! guards `GET /__capture/<file>` in `server.rs`.
//!
//! Frame layout is proven in `crate::kms` (`dbs_message_json` /
//! `dbs_data_frame`): 52-byte dbr.a header (from 6B | seq 8B BE | to 6B |
//! id 6B = to | msgType 42 | version 1 | zero tail) inside the NDSF sid-8
//! DATA wrapper (`>HH(len+2, 0x0020)`, payload `0x00` + `>H` tid 0x1001).
//! The parity test below pins these bytes against a golden generated by
//! the python script with a frozen clock.

use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};
use std::time::{Duration, SystemTime, UNIX_EPOCH};

use base64::{Engine as _, engine::general_purpose};
use serde_json::{Value, json};

/// Our fixed peer id on the DataBus session (castpush.py `PC`).
pub const PC_ID_HEX: &str = "A1B2C3D4E5F6";
/// Phone PDID, the fixed destination/id field (castpush.py `PHONE`).
pub const PHONE_ID_HEX: &str = "0123456789AB";
/// DataBus DATA frame transaction id used by the proven push path.
pub const TID: u16 = 0x1001;
/// EPI sink key substring that receives cast frames (the :46888 session).
pub const CAST_SINK_SUBSTR: &str = "46888";
/// Captured ODMF session log, the only files `GET /__capture/*` may serve.
pub const SESSION_BIN_NAME: &str = "odmf-session.bin";
/// Depacketized Annex-B H.265 written by the ODMF sink.
pub const VIDEO_NAME: &str = "video_odmf.h265";
/// Default KMS listen port (`KMS_PORT` in `main.rs` preflight).
pub const DEFAULT_KMS_PORT: u16 = 36863;
/// Default REPL port when `LPLUS_REPL_PORT` is unset.
pub const DEFAULT_REPL_PORT: u16 = 47991;

// ---------------------------------------------------------------- env facts
/// Parse one port env var, falling back to `default` on missing/garbage.
fn env_port(key: &str, default: u16) -> u16 {
    std::env::var(key)
        .ok()
        .and_then(|v| v.trim().parse::<u16>().ok())
        .unwrap_or(default)
}

/// `true` when the opt-in env flag is exactly `1` (sdpd/wfd_sink/rtsp
/// convention: `ODMF_SINK=1`, `RTSP=1`).
fn env_flag(key: &str) -> bool {
    std::env::var(key).map(|v| v.trim() == "1").unwrap_or(false)
}

fn env_or(key: &str, default: &str) -> String {
    std::env::var(key).unwrap_or_else(|_| default.to_string())
}

/// TCP port of the backend line REPL (panel Console tab dials it).
pub fn repl_port() -> u16 {
    env_port("LPLUS_REPL_PORT", DEFAULT_REPL_PORT)
}

/// TCP port of the PC-side KMS server (`lplus_status` probe target).
pub fn kms_port() -> u16 {
    env_port("KMS_PORT", DEFAULT_KMS_PORT)
}

/// Capture output dir of the ODMF sink: `ODMF_OUT` verbatim, else the
/// sink default `../capture` relative to the crate dir (process cwd).
pub fn out_dir() -> PathBuf {
    match std::env::var("ODMF_OUT") {
        Ok(v) if !v.trim().is_empty() => PathBuf::from(v.trim()),
        _ => std::env::current_dir()
            .unwrap_or_else(|_| PathBuf::from("."))
            .join("../capture"),
    }
}

// -------------------------------------------------------------- frame build
/// Decode a peer id hex string; fall back to `fallback` unless it is
/// exactly 6 bytes of hex (env overrides must never corrupt the header).
fn peer_id6(raw: &str, fallback: &[u8; 6]) -> [u8; 6] {
    hex::decode(raw.trim())
        .ok()
        .and_then(|b| <[u8; 6]>::try_from(b).ok())
        .unwrap_or(*fallback)
}

fn peer_ids() -> ([u8; 6], [u8; 6]) {
    let from = env_or("LINK_DET_PEER", PC_ID_HEX);
    let to = env_or("LINK_KPD", PHONE_ID_HEX);
    (
        peer_id6(&from, &hex_const(PC_ID_HEX)),
        peer_id6(&to, &hex_const(PHONE_ID_HEX)),
    )
}

fn hex_const(s: &str) -> [u8; 6] {
    // Constants above are fixed 12-hex-char literals; fall back to zeros
    // rather than panic if someone edits them wrongly.
    hex::decode(s)
        .ok()
        .and_then(|b| <[u8; 6]>::try_from(b).ok())
        .unwrap_or([0u8; 6])
}

/// Build the unencrypted DataBus DbsMessage frame the phone accepts on the
/// live :46888 session, byte-for-byte per castpush.py: DbsMessage JSON
/// (`key` / `value_json` payload) behind the 52-byte dbr.a header and the
/// sid-8 DATA wrapper, tid [`TID`].
pub fn dbs_frame(key: &str, value_json: &str, seq: u64) -> Vec<u8> {
    let (from6, to6) = peer_ids();
    let from_hex = hex::encode_upper(from6);
    let to_hex = hex::encode_upper(to6);
    let jsons =
        crate::kms::dbs_message_json("Oplus_Cast", &from_hex, &to_hex, key, value_json, seq);
    crate::kms::dbs_data_frame(&from6, &to6, seq, TID, jsons.as_bytes())
}

fn now_ms() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_millis() as u64)
        .unwrap_or(1)
}

/// Strictly increasing DataBus seq across pushes. The phone dedupes frames
/// by their seq-derived tid: two panel pushes 26 µs apart shared one tid
/// and the second frame was silently dropped (live 18:23:18Z).
fn next_seq() -> u64 {
    static LAST_SEQ: AtomicU64 = AtomicU64::new(0);
    let now = now_ms();
    loop {
        let last = LAST_SEQ.load(Ordering::SeqCst);
        let s = now.max(last + 1);
        if LAST_SEQ
            .compare_exchange_weak(last, s, Ordering::SeqCst, Ordering::SeqCst)
            .is_ok()
        {
            return s;
        }
    }
}

/// Push one DbsMessage key/value onto the live :46888 session through the
/// backend's [`crate::sdpd::Command::SendFrame`] broadcast (the REPL
/// `send 46888 <hex>` path, in-process). Returns the frame bytes and
/// whether the command was accepted by the backend channel.
pub fn push_value(key: &str, value_json: &str) -> (Vec<u8>, bool) {
    let frame = dbs_frame(key, value_json, next_seq());
    let queued = crate::sdpd::send_command(crate::sdpd::Command::SendFrame {
        key_substr: CAST_SINK_SUBSTR.to_string(),
        hex: hex::encode(&frame),
    });
    tracing::info!("[cast] push {key}: {}B queued={queued}", frame.len());
    (frame, queued)
}

// ----------------------------------------------------------- ipc channels
/// `cast_push {key, value}`: inject one DbsMessage frame and report the
/// live sink roster (best-effort REPL `list`) alongside the frame size.
pub fn cast_push(key: &str, value: &str) -> Value {
    if key.trim().is_empty() {
        return json!({ "ok": false, "error": "missing key" });
    }
    let (frame, queued) = push_value(key, value);
    let roster = crate::gui::ipc::repl_exec_line("list");
    json!({
        "ok": true,
        "key": key,
        "frame_bytes": frame.len(),
        "frame_hex": hex::encode(&frame),
        "queued": queued,
        "repl_out": roster.get("out").cloned().unwrap_or_else(|| json!([])),
    })
}

/// `odmf_start {}`: the two DataBus pushes that make the phone dial our
/// ODMF sink (screen-mirror trigger, live-verified 23:49 with the python
/// twin). Both MUST use the DbsMessage key `cast_ability_sync`: the phone's
/// `CastDbsReceiver` looks the key up in the `CastDispatchMessage` list and
/// anything else dispatches with type 0 and is silently dropped — the inner
/// `msg_cmd` is what routes inside `CastSceneManager.handleReceiveData`.
pub fn odmf_start() -> Value {
    let pub_file = env_or("ODMF_PUB_FILE", "/tmp/odmf_pub.b64");
    let raw = match std::fs::read_to_string(&pub_file) {
        Ok(raw) => raw,
        Err(e) => {
            tracing::warn!("[cast] odmf_start: cannot read public key {pub_file}: {e}");
            return json!({ "ok": false, "error": format!("missing ODMF public key ({pub_file})") });
        }
    };
    let n = next_seq();
    let id = general_purpose::STANDARD.encode(format!("lplus-pc-{n}"));
    let server_ip = env_or("LPLUS_PC_IP", &crate::sdpd::default_vip());
    let auth = json!({ "id": id, "public_key": raw.trim(), "auth_version": 1 }).to_string();
    // The sink must echo exactly this id (the phone compares raw bytes in
    // SigIdentityAuthHelper), so persist it for OdmfAuth::load()'s per-auth
    // reload. The keypair itself stays fixed (ODMF_PRIV_PEM ↔ pub file).
    let auth_file = env_or("ODMF_AUTH_FILE", "/tmp/odmf_authinfo.json");
    if let Err(e) = std::fs::write(&auth_file, &auth) {
        tracing::warn!("[cast] odmf_start: cannot write {auth_file}: {e}");
    }
    let (body1, body2) = odmf_bodies(&server_ip, &auth);
    let (_, q1) = push_value("cast_ability_sync", &body1);
    let (_, q2) = push_value("cast_ability_sync", &body2);
    json!({
        "ok": true,
        "id": id,
        "pushes": 2,
        "queued": [q1, q2],
        // The sink the phone will dial (what the GUI shows under the
        // mirroring toggle; `env_or` mirrors the sink's own defaults).
        "listen": env_or("ODMF_LISTEN", "0.0.0.0:7236"),
        "rtp_port": env_or("ODMF_RTP_PORT", "15550"),
    })
}

/// The two CastMessage JSON bodies of the ODMF trigger (pure, for tests).
/// `auth` is the serialized `{"id","public_key","auth_version"}` object.
fn odmf_bodies(server_ip: &str, auth: &str) -> (String, String) {
    let ability = json!({
        "device_type": "Win",
        // true = PC accepts the ODMF sink lane; the phone only dials our
        // 7236 TCP signaling port when this is true (live 23:48: with false
        // the phone logs isPcSupportOdmf=false and never dials).
        "pc_support_odmf": true,
        "castComponent": "",
        "castMode": 0,
        "audioPath": 0,
        "mirageFrom": 0,
    })
    .to_string();
    let rsp = json!({
        "client_id": 0,
        "component_name": "",
        "notifyKey": "",
        "odmf_auth_info": auth,
        "port": 7236,
        "privacyProtect": false,
        "server_ip": server_ip,
    })
    .to_string();
    // Live transcript 18:43Z: the phone's CastSceneDispatcher routes on
    // `msg_type`/`msg_cmd` — the DbsMessage *value* must be the full
    // CastMessage envelope `{"msg_type":50,"msg_cmd":<cmd>,"msg_body":<json
    // string>}`; a bare body parses as msg type 0 and is silently dropped.
    (
        cast_message("pc_devicetype_supportodmf", &ability),
        cast_message("rsp_odmf_key", &rsp),
    )
}

/// CastMessage envelope for a msg_type 50 (scene dispatch) push.
fn cast_message(msg_cmd: &str, msg_body: &str) -> String {
    json!({ "msg_type": 50, "msg_cmd": msg_cmd, "msg_body": msg_body }).to_string()
}

// -------------------------------------------------------------- status/ops
/// `lplus_status {}`: env-read snapshot of backend liveness, REPL/KMS
/// lanes, ODMF sink files and the RTSP lane. Never panics; the KMS probe
/// is bounded to 300 ms.
pub fn status_json() -> Value {
    let out = out_dir();
    json!({
        "ok": true,
        "backend_up": crate::gui::backend_up(),
        "repl_port": repl_port(),
        "repl_enabled": std::env::var("LPLUS_REPL_PORT").is_ok(),
        "kms_listening": tcp_probe(kms_port()),
        "odmf": {
            "enabled": env_flag("ODMF_SINK"),
            "listen": env_or("ODMF_LISTEN", "0.0.0.0:7236"),
            "rtp_port": env_or("ODMF_RTP_PORT", "15550"),
            "out_dir": out.display().to_string(),
            "session_bin": file_info(&out.join(SESSION_BIN_NAME)),
            "video": file_info(&out.join(VIDEO_NAME)),
        },
        "rtsp": {
            "enabled": env_flag("RTSP"),
            "target": env_or("RTSP_TARGET", ""),
        },
    })
}

fn file_info(path: &Path) -> Value {
    match std::fs::metadata(path) {
        Ok(md) => {
            let secs = md
                .modified()
                .ok()
                .and_then(|t| t.duration_since(UNIX_EPOCH).ok())
                .map(|d| d.as_secs())
                .unwrap_or(0);
            json!({ "exists": true, "size": md.len(), "mtime_secs": secs })
        }
        Err(_) => json!({ "exists": false, "size": 0, "time": Value::Null }),
    }
}

/// Nonblocking TCP liveness probe of a loopback listener, 300 ms cap.
fn tcp_probe(port: u16) -> bool {
    let addr = std::net::SocketAddr::from(([127, 0, 0, 1], port));
    std::net::TcpStream::connect_timeout(&addr, Duration::from_millis(300)).is_ok()
}

// ---------------------------------------------------------------- capture
/// Whitelisted capture artifact names for `GET /__capture/<name>`.
pub const CAPTURE_FILES: [&str; 2] = [SESSION_BIN_NAME, VIDEO_NAME];

/// Resolve one whitelisted capture artifact inside `out_dir`. Anything not
/// exactly listed (traversal, absolute paths, subdirs) or missing on disk
/// resolves to `None` — the route then answers 404.
pub fn capture_file(out_dir: &Path, name: &str) -> Option<PathBuf> {
    if !CAPTURE_FILES.contains(&name) {
        return None;
    }
    let file = out_dir.join(name);
    file.is_file().then_some(file)
}

